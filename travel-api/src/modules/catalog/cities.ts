export function findCity(id: string): City | undefined {
  return cities.find((city) => city.id === id);
}

export function findCityByName(name: string): City | undefined {
  const normalized = name.trim().toLocaleLowerCase("ru");
  return cities.find(
    (city) =>
      city.name.toLocaleLowerCase("ru") === normalized ||
      city.id.toLocaleLowerCase("ru") === normalized,
  );
}
